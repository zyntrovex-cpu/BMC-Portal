<?php
require_once __DIR__ . '/../includes/auth.php';
require_once __DIR__ . '/../includes/functions.php';
require_once __DIR__ . '/../../config/config.php';

$user = requireAuth('student_affairs');
$db   = getDB();

$classId   = (int)($_GET['class_id']   ?? 0);
$subjectId = (int)($_GET['subject_id'] ?? 0);

if (!$classId || !$subjectId) {
    redirect('/portal/student-affairs/results.php');
}

function saGrade(float $pct): string {
    if ($pct >= 95) return 'A++';
    if ($pct >= 90) return 'A+';
    if ($pct >= 85) return 'A';
    if ($pct >= 80) return 'B++';
    if ($pct >= 75) return 'B+';
    if ($pct >= 70) return 'B';
    if ($pct >= 60) return 'C';
    if ($pct >= 50) return 'D';
    if ($pct >= 40) return 'E';
    return 'U';
}

$assessments    = [];
$studentResults = [];
$className      = '';
$subjectName    = '';

$clRow = $db->prepare('SELECT name FROM classes WHERE id = ?');
$clRow->execute([$classId]);
$className = ($clRow->fetch()['name'] ?? '');

$subRow = $db->prepare('SELECT name FROM subjects WHERE id = ?');
$subRow->execute([$subjectId]);
$subjectName = ($subRow->fetch()['name'] ?? '');

$aSt = $db->prepare('SELECT * FROM assessments WHERE class_id = ? AND subject_id = ? ORDER BY date');
$aSt->execute([$classId, $subjectId]);
$assessments = $aSt->fetchAll();

if (!empty($assessments)) {
    $students = getClassStudents($classId);
    $aIds         = array_column($assessments, 'id');
    $placeholders = implode(',', array_fill(0, count($aIds), '?'));
    $marksSt      = $db->prepare("SELECT assessment_id, student_id, marks_obtained FROM marks WHERE assessment_id IN ($placeholders)");
    $marksSt->execute($aIds);
    $marksMap = [];
    foreach ($marksSt->fetchAll() as $m) {
        $marksMap[$m['student_id']][$m['assessment_id']] = $m['marks_obtained'];
    }
    foreach ($students as $s) {
        $totalWeight   = 0;
        $totalWeighted = 0;
        $row = ['student' => $s, 'marks' => [], 'overall_pct' => null];
        foreach ($assessments as $a) {
            $obtained = $marksMap[$s['id']][$a['id']] ?? null;
            $pct = ($obtained !== null && $a['max_marks'] > 0)
                 ? round($obtained / $a['max_marks'] * 100, 1) : null;
            $row['marks'][$a['id']] = ['obtained' => $obtained, 'pct' => $pct];
            if ($obtained !== null) {
                $totalWeighted += $pct * $a['weight'];
                $totalWeight   += $a['weight'];
            }
        }
        if ($totalWeight > 0) {
            $row['overall_pct'] = round($totalWeighted / $totalWeight, 1);
        }
        $studentResults[] = $row;
    }
}

$filename = 'Results_' . preg_replace('/[^A-Za-z0-9_]/', '_', $className) . '_' . preg_replace('/[^A-Za-z0-9_]/', '_', $subjectName) . '.doc';

