      </td>
      <?php endforeach; ?>
      <td class="center"><?= $r['overall_pct'] !== null ? $r['overall_pct'].'%' : '—' ?></td>
      <td class="center"><?= $r['overall_pct'] !== null ? saGrade((float)$r['overall_pct']) : '—' ?></td>
